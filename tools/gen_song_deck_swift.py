"""Writes the phone's Guess the Song deck from the server's word list.

    python3 tools/gen_song_deck_swift.py

games/native_hub/engines/_song_words.py holds the decks; this copies them into
ios/GameLabController/Views/PhonePlay/GuessSong/GuessSongDeck.swift so the
phone can play offline. tests/test_phone_guess_song.py fails if they drift.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
OUT = ROOT / "ios" / "GameLabController" / "Views" / "PhonePlay" / "GuessSong" / "GuessSongDeck.swift"


def swift_string(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def render() -> str:
    from games.native_hub.engines._song_words import DECKS
    lines = [
        "// Generated by tools/gen_song_deck_swift.py from",
        "// games/native_hub/engines/_song_words.py. Do not edit by hand: add a",
        "// theme there (DECKS) and run the tool.",
        "",
        "struct GuessSongWord: Equatable {",
        "    let word: String",
        "    /// The word in the deck's language; empty for a deck without hints.",
        "    let hint: String",
        "    let songs: [String]",
        "}",
        "",
        "struct GuessSongTheme: Identifiable, Equatable {",
        "    let id: String",
        "    let title: String",
        "    let symbol: String",
        "    /// \"Hindi\", \"Telugu\"... empty when the deck has no hints.",
        "    let hintLabel: String",
        "    let words: [GuessSongWord]",
        "}",
        "",
        "enum GuessSongDeck {",
        "    static let themes: [GuessSongTheme] = [",
    ]
    for deck_id, deck in DECKS.items():
        lines.append(f"        GuessSongTheme(id: {swift_string(deck_id)}, title: {swift_string(deck['title'])}, "
                     f"symbol: {swift_string(deck['symbol'])}, hintLabel: {swift_string(deck['hintLabel'])}, words: [")
        for entry in deck["words"]:
            songs = ", ".join(swift_string(s) for s in entry["songs"])
            lines.append(f"            GuessSongWord(word: {swift_string(entry['word'])}, "
                         f"hint: {swift_string(entry['hint'])}, songs: [{songs}]),")
        lines.append("        ]),")
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
