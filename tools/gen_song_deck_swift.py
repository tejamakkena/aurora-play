"""Writes the phone's Guess the Song deck from the server's word list.

    python3 tools/gen_song_deck_swift.py

games/native_hub/engines/_song_words.py is the one list; this copies it into
ios/GameLabController/Views/PhonePlay/GuessSong/GuessSongDeck.swift so the
phone can play offline. tests/test_phone_guess_song.py fails if they drift.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
OUT = ROOT / "ios" / "GameLabController" / "Views" / "PhonePlay" / "GuessSong" / "GuessSongDeck.swift"


def swift_string(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def render() -> str:
    from games.native_hub.engines._song_words import WORDS
    lines = [
        "// Generated by tools/gen_song_deck_swift.py from",
        "// games/native_hub/engines/_song_words.py. Do not edit by hand.",
        "",
        "struct GuessSongWord: Equatable {",
        "    let word: String",
        "    let hindi: String",
        "    let songs: [String]",
        "}",
        "",
        "enum GuessSongDeck {",
        "    static let words: [GuessSongWord] = [",
    ]
    for entry in WORDS:
        songs = ", ".join(swift_string(s) for s in entry["songs"])
        lines.append(f"        GuessSongWord(word: {swift_string(entry['word'])}, "
                     f"hindi: {swift_string(entry['hindi'])}, songs: [{songs}]),")
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
