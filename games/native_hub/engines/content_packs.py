PACKS = {
    "en": {
        # Resolved lazily (see _english_trivia_pool) to avoid a circular
        # import with legacy_social.py.
        "trivia": None,
        "kbc": list(_C.KBC_QUESTIONS),
    },
    "te": {
        "trivia": list(TE_TRIVIA),
        "kbc": list(TE_KBC),
    },
    "hi": {
        "trivia": list(HI_TRIVIA),
        "kbc": list(HI_KBC),
    },
}


def questions_for(pack_id: str, kind: str) -> list:
    """Return the question pool for a language pack and kind.

    Unknown pack ids fall back to English so a room configured with a pack
    that is not installed yet still gets a playable game.
    """
    pack = PACKS.get(pack_id, PACKS["en"])
    pool = pack[kind]
    if pool is None:
        pool = _english_trivia_pool()
    return pool


#: How many recently-asked questions a room remembers per (pack, kind).
#: With banks of 100+ questions this is plenty to keep back-to-back
#: sessions from replaying the same round.
RECENT_HISTORY_CAP = 60


def _question_text(kind: str, item) -> str:
    """The dedupe key for one question tuple.

    Trivia tuples are (category, question, options, answer_index); KBC
    tuples (and trivia questions widened into the KBC pool) are
    (question, options, answer_index).
    """
    return item[1] if kind == "trivia" else item[0]


def fresh_questions(room, pack_id: str, kind: str, pool=None) -> list:
    """Question pool for a new quiz session, skipping the room's recent history.

    Questions asked in this room's recent sessions (see record_questions)
    are excluded so a second game doesn't replay the first. If the history
    would leave fewer than a quarter of the bank, the full bank is returned
    instead -- a full pool with a few repeats beats a starved one.
    """
    bank = list(pool) if pool is not None else list(questions_for(pack_id, kind))
    seen = set(getattr(room, "question_history", {}).get((pack_id, kind), ()))
    if not seen:
        return bank
    fresh = [q for q in bank if _question_text(kind, q) not in seen]
    if len(fresh) < max(1, len(bank) // 4):
        return bank
    return fresh


def record_questions(room, pack_id: str, kind: str, questions) -> None:
    """Append asked questions to the room's rolling recent-history.

    Most-recent last, capped at RECENT_HISTORY_CAP per (pack, kind); a
    re-asked question moves to the back of the queue.
    """
    history = getattr(room, "question_history", None)
    if history is None:
        room.question_history = {}
        history = room.question_history
    current = history.setdefault((pack_id, kind), [])
    for q in questions:
        text = _question_text(kind, q)
        if text in current:
            current.remove(text)
        current.append(text)
    del current[:-RECENT_HISTORY_CAP]
