"""Localised question packs for the party quiz engines.

Each pack is keyed by a short language id and holds the same two question
kinds the engines already consume:

* "trivia" -- 4-tuples of (category, question, options, answer_index),
  exactly the shape of TRIVIA_QUESTIONS in legacy_social.py.
* "kbc" -- 3-tuples of (question, options, answer_index),
  exactly the shape of KBC_QUESTIONS in _content.py.

The English pack reuses the existing tables by reference, so the default
path is byte-for-byte the old behaviour. Telugu and Hindi packs add
original questions written for this project.

TRIVIA_QUESTIONS is imported lazily because legacy_social.py imports
questions_for from this module at its top level -- a top-level import
here would be circular.
"""

