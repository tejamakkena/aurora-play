PACKS = {
    "en": {
        # Resolved lazily (see _english_trivia_pool) to avoid a circular
        # import with legacy_social.py.
        "trivia": None,
        "kbc": list(_C.KBC_QUESTIONS),
    },
    "te": {
        "trivia": list(TE_TRIVIA),
        "kbc": list(TE_KBC),
    },
    "hi": {
        "trivia": list(HI_TRIVIA),
        "kbc": list(HI_KBC),
    },
}


def questions_for(pack_id: str, kind: str) -> list:
    """Return the question pool for a language pack and kind.

    Unknown pack ids fall back to English so a room configured with a pack
    that is not installed yet still gets a playable game.
    """
    pack = PACKS.get(pack_id, PACKS["en"])
    pool = pack[kind]
    if pool is None:
        pool = _english_trivia_pool()
    return pool
